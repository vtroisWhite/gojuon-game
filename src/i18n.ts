export const dictionaries: Record<Language, Dictionary> = { 'zh-CN': zh, en };
export function categoryLabel(category: Category, language: Language) {
  const [script, group] = category.split('-') as [
    'hiragana' | 'katakana',
    'seion' | 'dakuten' | 'yoon',
  ];
  const t = dictionaries[language];
  return `${t[script]} · ${t[group]}`;
}
export function modeLabel(mode: Mode, language: Language) {
  const t = dictionaries[language];
  return mode === 'mixed' ? t.mixed : mode === 'kana-romaji' ? t.forward : t.reverse;
}
export function formatTime(ms: number, language: Language) {
  const t = dictionaries[language];
  const seconds = Math.floor(ms / 1000);
  return `${Math.floor(seconds / 60)}${t.min} ${seconds % 60}${t.sec}`;
}
export function accuracy(correct: number, answered: number) {
  return answered ? `${Math.round((correct / answered) * 100)}%` : '—';
}
